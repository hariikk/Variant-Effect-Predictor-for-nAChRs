"""
Export the clean variant dataset to dashboard/variants.js for the offline HTML explorer.

Loads the same 760-row dataset used by the static spread-plots (final_mapped.xlsx via
load_mutation_data), adds a gene-family column, and writes a single JS file:

    const VARIANTS = [ {g, f, p, e, s, w, m, path, pmid}, ... ];
    const META     = { genes, familyNames, familyOf, colors, effectOrder, speciesOrder };

The palettes are copied from scripts/make_spread_plots.py so the dashboard and PNGs match.

Run whenever final_mapped.xlsx changes:  python scripts/export_variants_json.py
"""

import json
import sys
import warnings
from pathlib import Path

import pandas as pd

sys.stdout.reconfigure(encoding="utf-8")
warnings.filterwarnings("ignore")

from vep_nachr2.data.loader import load_mutation_data
from vep_nachr2.data.viz_clean import clean_variants, conflicting_rows

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "dashboard"
OUT_JS = OUT_DIR / "variants.js"

EFFECT_ORDER = ["LOF", "No net effect", "GOF"]
SPECIES_ORDER = ["human", "rat", "mouse"]
GENE_ORDER = [
    "CHRNA1", "CHRNA2", "CHRNA3", "CHRNA4", "CHRNA5", "CHRNA6", "CHRNA7",
    "CHRNA9", "CHRNA10",
    "CHRNB1", "CHRNB2", "CHRNB3", "CHRNB4",
    "CHRND", "CHRNE", "CHRNG",
]

FAMILY_NAMES = {"alpha": "α family", "beta": "β family", "dge": "δ / γ / ε family"}

EFFECT_COLOR = {
    "LOF": "#377eb8",            # blue  (bottom, loss)
    "No net effect": "#999999",  # grey  (middle, neutral)
    "GOF": "#e41a1c",            # red   (top, gain)
}

GENE_COLOR = {
    "CHRNA1": "#1f77b4", "CHRNA2": "#ff7f0e", "CHRNA3": "#2ca02c",
    "CHRNA4": "#d62728", "CHRNA5": "#9467bd", "CHRNA6": "#8c564b",
    "CHRNA7": "#e377c2", "CHRNA9": "#7f7f7f", "CHRNA10": "#bcbd22",
    "CHRNB1": "#1f77b4", "CHRNB2": "#ff7f0e", "CHRNB3": "#2ca02c",
    "CHRNB4": "#d62728",
    "CHRND": "#1f77b4", "CHRNE": "#ff7f0e", "CHRNG": "#2ca02c",
}

SPECIES_COLOR = {"human": "#1f77b4", "rat": "#ff7f0e", "mouse": "#2ca02c"}


def family(gene: str) -> str:
    if gene.startswith("CHRNA"):
        return "alpha"
    if gene.startswith("CHRNB"):
        return "beta"
    return "dge"  # delta (CHRND), gamma (CHRNG), epsilon (CHRNE)


def _clean(value):
    """NaN/None -> null so json.dumps emits valid JSON."""
    if value is None:
        return None
    try:
        if pd.isna(value):
            return None
    except (TypeError, ValueError):
        pass
    return value


def main():
    raw = load_mutation_data(data_file="final_mapped.xlsx")
    conflicts = conflicting_rows(raw)
    if len(conflicts):
        n_ambig = conflicts.groupby(
            ["subunit", "position", "wildtype_aa", "variant_aa"]
        ).ngroups
        print(f"dropping {len(conflicts)} rows spanning {n_ambig} ambiguous "
              f"(multi-effect) mutations:\n{conflicts.to_string(index=False)}\n")
    df = clean_variants(raw)
    print(f"clean (one row per mutation) variants: {len(df)}")

    variants = []
    for _, r in df.iterrows():
        variants.append({
            "g": r["subunit"],
            "f": family(r["subunit"]),
            "p": int(r["position"]),
            "e": r["effect"],
            "s": r["species"],
            "w": r["wildtype_aa"],
            "m": r["variant_aa"],
            "path": _clean(r["pathology"]),
            "pmid": _clean(r["pmid"]),
        })

    # stable order: family -> gene -> position -> variant
    family_rank = {"alpha": 0, "beta": 1, "dge": 2}
    variants.sort(key=lambda v: (family_rank[v["f"]],
                                 GENE_ORDER.index(v["g"]),
                                 v["p"], v["m"]))

    meta = {
        "genes": GENE_ORDER,
        "familyNames": FAMILY_NAMES,
        "familyOf": {g: family(g) for g in GENE_ORDER},
        "colors": {
            "effect": EFFECT_COLOR,
            "gene": GENE_COLOR,
            "species": SPECIES_COLOR,
        },
        "effectOrder": EFFECT_ORDER,
        "speciesOrder": SPECIES_ORDER,
    }

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    js = (
        "// Auto-generated by scripts/export_variants_json.py — do not edit by hand.\n"
        "const VARIANTS = " + json.dumps(variants, ensure_ascii=False) + ";\n"
        "const META = " + json.dumps(meta, ensure_ascii=False) + ";\n"
    )
    OUT_JS.write_text(js, encoding="utf-8")
    print(f"wrote {OUT_JS} ({len(variants)} variants)")


if __name__ == "__main__":
    main()
